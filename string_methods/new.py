a = "Bhavani Mohan"
print(a.upper()) # Converts the string to uppercase

print(a.lower()) # Converts the string to lowercase

print(a.title()) # Converts the string to title case

print(a.isupper()) # Checks if the string is in uppercase

print(a.islower()) # Checks if the string is in lowercase

print(a.istitle()) # Checks if the string is in title case

print(a.startswith("Bha")) # Checks if the string starts with "Bha"

print(a.endswith("Mohan")) # Checks if the string ends with "Mohan"

print(a.replace("Mohan", "Kumar")) # Replaces "Mohan" with "Kumar"